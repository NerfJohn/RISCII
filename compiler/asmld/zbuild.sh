#!/usr/bin/env bash
# ===========================================================================
#  zbuild.sh - generate inc/version.h, build with CMake, move exe to output/
#
#  Usage:
#    ./zbuild.sh             version taken from the most recent matching git tag
#    ./zbuild.sh v1.4.0      manual version (always treated as a dirty build)
#
#  Settings (exe name, tag prefix, folders) are in zhead.sh.
#  A manual version can also be set with  MANUAL_VERSION=v1.4.0 ./zbuild.sh
# ===========================================================================
set -euo pipefail
ZSCRIPT=zbuild

cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" || { echo "cannot enter project root" >&2; exit 1; }
source ./zhead.sh

MANUAL_VERSION="${MANUAL_VERSION:-}"
[[ $# -gt 0 && -n "$1" ]] && MANUAL_VERSION="$1"

VER_NUMBER="v0.0.0"
VER_HASH=""
VER_DATE=""
DIRTY=0

# ===========================================================================
#  1. Determine version number
# ===========================================================================
if [[ -n "$MANUAL_VERSION" ]]; then
    is_valid_version "$MANUAL_VERSION" || fail "\"$MANUAL_VERSION\" is not of the form vX.X.X"
    VER_NUMBER="$MANUAL_VERSION"
    DIRTY=1

elif ! in_git_repo; then
    warn "not a git repository - building as devbuild v0.0.0"
    DIRTY=1

elif ! VER_TAG="$(latest_reachable_tag)"; then
    warn "no tag matching \"${TAG_PREFIX}vX.X.X\" found - building as devbuild v0.0.0"
    DIRTY=1

else
    VER_NUMBER="${VER_TAG#"$TAG_PREFIX"}"
    # Short hash of the tagged commit (7 chars, like GitHub)
    VER_HASH="$(git rev-list -n 1 --abbrev-commit --abbrev=7 "$VER_TAG")"
    # Tag date (tagger date for annotated tags, commit date for lightweight)
    VER_DATE="$(git for-each-ref --format='%(creatordate:short)' "refs/tags/$VER_TAG")"
    project_dirty && DIRTY=1
fi

if [[ "$DIRTY" -eq 1 ]]; then
    VER_HASH="devbuild"
    VER_DATE="$(date +%Y-%m-%d)"
fi

# ===========================================================================
#  2. Write the version header (only touched if the contents changed,
#     so unchanged builds don't trigger a recompile)
# ===========================================================================
mkdir -p "$(dirname "$VERSION_HEADER")"
TMP_HDR="$(mktemp)"
trap 'rm -f "$TMP_HDR"' EXIT

cat > "$TMP_HDR" <<EOF
#ifndef VERSION_H
#define VERSION_H

/* Auto-generated by zbuild.sh - do not edit. */
#define VERSION_NUMBER "$VER_NUMBER"
#define VERSION_HASH   "$VER_HASH"
#define VERSION_DATE   "$VER_DATE"

#endif /* VERSION_H */
EOF

cmp -s "$TMP_HDR" "$VERSION_HEADER" || cp "$TMP_HDR" "$VERSION_HEADER"

log "Version: $VER_NUMBER  Hash: $VER_HASH  Date: $VER_DATE"

# ===========================================================================
#  3. Build
# ===========================================================================
cmake -S . -B "$BUILD_DIR" -G "$CMAKE_GENERATOR" -DEXEC_NAME="$EXEC_NAME" || fail "CMake configure failed"
cmake --build "$BUILD_DIR" || fail "CMake build failed"

# ===========================================================================
#  4. Move executable to output/
# ===========================================================================
EXE="$(exe_path "$BUILD_DIR")" || fail "$BUILD_DIR/$EXEC_NAME(.exe) was not produced"
mkdir -p "$OUTPUT_DIR"
mv -f "$EXE" "$OUTPUT_DIR/"

log "Done: $OUTPUT_DIR/$(basename "$EXE")"
